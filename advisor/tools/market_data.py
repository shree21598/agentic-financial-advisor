"""Market-data tools backed by a local CSV of daily closes.

The bundled file ``data/sample_prices_synthetic.csv`` is SYNTHETIC (generated by
``scripts/generate_sample_prices.py``) so the project runs offline and evals are
reproducible. Swap in real data by writing a CSV with the same columns
(date,ticker,close) and pointing PRICES_CSV at it.
"""
from __future__ import annotations

import csv
import math
import os
from functools import lru_cache

import numpy as np

from advisor.config import DATA_DIR

TRADING_DAYS = 252


@lru_cache(maxsize=1)
def _prices_path() -> str:
    return os.getenv("PRICES_CSV", str(DATA_DIR / "sample_prices_synthetic.csv"))


def _load() -> dict[str, list[tuple[str, float]]]:
    path = _prices_path()
    series: dict[str, list[tuple[str, float]]] = {}
    with open(path, newline="") as f:
        for row in csv.DictReader(f):
            series.setdefault(row["ticker"].upper(), []).append((row["date"], float(row["close"])))
    for v in series.values():
        v.sort()
    return series


def available_tickers() -> list[str]:
    return sorted(_load())


def _closes(ticker: str, period_days: int) -> np.ndarray:
    data = _load().get(ticker.upper())
    if not data:
        raise ValueError(f"Unknown ticker {ticker!r}. Available: {', '.join(available_tickers())}")
    return np.array([c for _, c in data[-(period_days + 1):]])


def get_price_history(ticker: str, period_days: int = 252) -> dict:
    """Summarise recent price history for a ticker (return, volatility, drawdown).

    Args:
        ticker: Symbol, e.g. "VTI", "BND", "QQQ".
        period_days: Number of trading days to look back (252 ~ 1 year).
    """
    period_days = max(5, min(int(period_days), 2520))
    c = _closes(ticker, period_days)
    rets = np.diff(np.log(c))
    peak = np.maximum.accumulate(c)
    data = _load()[ticker.upper()]
    return {
        "ticker": ticker.upper(),
        "start_date": data[-len(c)][0],
        "end_date": data[-1][0],
        "start_price": round(float(c[0]), 2),
        "last_price": round(float(c[-1]), 2),
        "period_return_pct": round(float(c[-1] / c[0] - 1) * 100, 2),
        "annualized_volatility_pct": round(float(rets.std(ddof=1) * math.sqrt(TRADING_DAYS)) * 100, 2),
        "max_drawdown_pct": round(float((c / peak - 1).min()) * 100, 2),
        "data_note": "synthetic sample data" if "synthetic" in _prices_path() else "user-supplied data",
    }


def portfolio_metrics(holdings: dict, period_days: int = 756, risk_free_rate_pct: float = 2.0) -> dict:
    """Compute risk/return metrics for a weighted portfolio of tickers.

    Returns annualised return, volatility, Sharpe ratio, max drawdown and the
    pairwise correlation matrix. Weights are normalised to sum to 1.

    Args:
        holdings: Mapping of ticker -> weight, e.g. {"VTI": 0.6, "BND": 0.4}.
        period_days: Look-back window in trading days (756 ~ 3 years).
        risk_free_rate_pct: Annual risk-free rate in percent, for the Sharpe ratio.
    """
    if not holdings:
        raise ValueError("holdings must not be empty")
    tickers = [t.upper() for t in holdings]
    w = np.array([float(v) for v in holdings.values()])
    if (w < 0).any() or w.sum() <= 0:
        raise ValueError("weights must be non-negative and sum to > 0")
    w = w / w.sum()
    n = min(int(period_days), *(len(_load()[t]) - 1 for t in tickers if t in _load()))
    rets = np.vstack([np.diff(_closes(t, n)) / _closes(t, n)[:-1] for t in tickers])
    port = w @ rets
    ann_ret = (np.prod(1 + port) ** (TRADING_DAYS / len(port)) - 1) * 100
    ann_vol = port.std(ddof=1) * math.sqrt(TRADING_DAYS) * 100
    wealth = np.cumprod(1 + port)
    mdd = (wealth / np.maximum.accumulate(wealth) - 1).min() * 100
    corr = np.corrcoef(rets) if len(tickers) > 1 else np.array([[1.0]])
    return {
        "weights": {t: round(float(x), 4) for t, x in zip(tickers, w)},
        "period_days": int(n),
        "annualized_return_pct": round(float(ann_ret), 2),
        "annualized_volatility_pct": round(float(ann_vol), 2),
        "sharpe_ratio": round(float((ann_ret - risk_free_rate_pct) / ann_vol), 2) if ann_vol else None,
        "max_drawdown_pct": round(float(mdd), 2),
        "correlation": {
            a: {b: round(float(corr[i, j]), 2) for j, b in enumerate(tickers)} for i, a in enumerate(tickers)
        },
    }
